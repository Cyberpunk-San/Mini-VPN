/* Vendor-side license tool. NOT shipped to customers.
 *
 *   license-tool keygen [--force]        create vendor/license-signing.key and src/license_pubkey.h
 *   license-tool sign --customer NAME --devices N [--days 365] [--edition business]
 *                     [--key vendor/license-signing.key] [--issued YYYY-MM-DD]
 *   license-tool verify FILE             check a license against the compiled-in public key
 *
 * Keep vendor/license-signing.key secret and backed up: anyone holding it can
 * mint licenses, and losing it means existing builds can't accept new ones. */

#include "crypto.h"
#include "license.h"
#include "log.h"
#include "util.h"

#include <errno.h>
#include <fcntl.h>
#include <getopt.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#include <time.h>
#include <unistd.h>

#define DEFAULT_KEY    "vendor/license-signing.key"
#define DEFAULT_HEADER "src/license_pubkey.h"

static int write_file(const char *path, const char *data, mode_t mode, int force)
{
    int flags = O_WRONLY | O_CREAT | O_TRUNC | (force ? 0 : O_EXCL);
    int fd = open(path, flags, mode);
    if (fd < 0) {
        fprintf(stderr, "cannot write %s: %s%s\n", path, strerror(errno),
                errno == EEXIST ? " (use --force to replace it; old licenses stop working)" : "");
        return -1;
    }
    size_t len = strlen(data);
    int ok = write(fd, data, len) == (ssize_t)len && fsync(fd) == 0;
    close(fd);
    return ok ? 0 : -1;
}

static int cmd_keygen(int argc, char **argv)
{
    int force = argc > 1 && !strcmp(argv[1], "--force");
    uint8_t priv[KEY_LEN], pub[KEY_LEN];
    char hex[2 * KEY_LEN + 2], header[1024];

    if (ed25519_keygen(priv, pub)) {
        fprintf(stderr, "key generation failed\n");
        return 1;
    }
    mkdir("vendor", 0700);
    hex_encode(priv, KEY_LEN, hex);
    strcat(hex, "\n");
    if (write_file(DEFAULT_KEY, hex, 0600, force))
        return 1;

    int n = snprintf(header, sizeof header,
                     "/* Vendor license-verification key. Generated by `make vendor-key`;\n"
                     " * the matching private key is vendor/license-signing.key. */\n"
                     "#ifndef MINIVPN_LICENSE_PUBKEY_H\n#define MINIVPN_LICENSE_PUBKEY_H\n\n"
                     "#include <stdint.h>\n\nstatic const uint8_t LICENSE_PUBKEY[32] = {");
    for (int i = 0; i < KEY_LEN; i++)
        n += snprintf(header + n, sizeof header - (size_t)n, "%s0x%02x",
                      i == 0 ? "\n    " : i % 8 ? ", " : ",\n    ", pub[i]);
    snprintf(header + n, sizeof header - (size_t)n, ",\n};\n\n#endif\n");
    if (write_file(DEFAULT_HEADER, header, 0644, 1))
        return 1;

    secure_zero(priv, sizeof priv);
    secure_zero(hex, sizeof hex);
    printf("wrote %s (secret, keep it safe) and %s; rebuild minivpn to embed the new public key\n",
           DEFAULT_KEY, DEFAULT_HEADER);
    return 0;
}

static int load_private_key(const char *path, uint8_t priv[KEY_LEN])
{
    char buf[256];
    int fd = open(path, O_RDONLY);
    if (fd < 0) {
        fprintf(stderr, "cannot open %s: %s\n", path, strerror(errno));
        return -1;
    }
    ssize_t n = read(fd, buf, sizeof buf - 1);
    close(fd);
    if (n < 0)
        return -1;
    buf[n] = '\0';
    int rc = hex_decode(buf, priv, KEY_LEN);
    secure_zero(buf, sizeof buf);
    if (rc)
        fprintf(stderr, "%s is not a valid signing key\n", path);
    return rc;
}

static int cmd_sign(int argc, char **argv)
{
    static const struct option opts[] = {
        { "customer", required_argument, NULL, 'c' },
        { "devices", required_argument, NULL, 'n' },
        { "days", required_argument, NULL, 'd' },
        { "edition", required_argument, NULL, 'e' },
        { "key", required_argument, NULL, 'k' },
        { "issued", required_argument, NULL, 'i' },
        { 0 },
    };
    const char *key_path = DEFAULT_KEY;
    long days = 365;
    license_fields f;
    int opt;

    memset(&f, 0, sizeof f);
    snprintf(f.edition, sizeof f.edition, "business");
    time_t now = time(NULL);
    struct tm tm;
    gmtime_r(&now, &tm);
    strftime(f.issued, sizeof f.issued, "%Y-%m-%d", &tm);

    while ((opt = getopt_long(argc, argv, "c:n:d:e:k:i:", opts, NULL)) != -1) {
        switch (opt) {
        case 'c': snprintf(f.customer, sizeof f.customer, "%s", optarg); break;
        case 'n': snprintf(f.max_devices, sizeof f.max_devices, "%s", optarg); break;
        case 'd': days = strtol(optarg, NULL, 10); break;
        case 'e': snprintf(f.edition, sizeof f.edition, "%s", optarg); break;
        case 'k': key_path = optarg; break;
        case 'i': snprintf(f.issued, sizeof f.issued, "%s", optarg); break;
        default: return 2;
        }
    }
    if (days < 1 || days > 3650) {
        fprintf(stderr, "--days must be 1..3650\n");
        return 2;
    }

    /* expires = issued + days, computed in UTC */
    memset(&tm, 0, sizeof tm);
    if (!strptime(f.issued, "%Y-%m-%d", &tm)) {
        fprintf(stderr, "--issued must be YYYY-MM-DD\n");
        return 2;
    }
    time_t t = timegm(&tm) + days * 86400;
    gmtime_r(&t, &tm);
    strftime(f.expires, sizeof f.expires, "%Y-%m-%d", &tm);

    uint8_t idbytes[8];
    char idhex[17];
    crypto_random(idbytes, sizeof idbytes);
    hex_encode(idbytes, sizeof idbytes, idhex);
    snprintf(f.license_id, sizeof f.license_id, "LIC-%s", idhex);

    const char *err = license_fields_error(&f);
    if (err) {
        fprintf(stderr, "invalid license: %s\n", err);
        return 2;
    }

    uint8_t priv[KEY_LEN], sig[SIG_LEN];
    char canon[512];
    if (load_private_key(key_path, priv))
        return 1;
    int len = license_canonical(&f, canon, sizeof canon);
    int rc = len < 0 || ed25519_sign(priv, (const uint8_t *)canon, (size_t)len, sig);
    secure_zero(priv, sizeof priv);
    if (rc) {
        fprintf(stderr, "signing failed\n");
        return 1;
    }
    hex_encode(sig, SIG_LEN, f.signature);

    printf("# minivpn license. Install as /etc/minivpn/license.key, then: minivpn-admin reload\n"
           "# Any change to this file invalidates the signature.\n"
           "customer = %s\nedition = %s\nmax_devices = %s\nissued = %s\nexpires = %s\nlicense_id = %s\nsignature = %s\n",
           f.customer, f.edition, f.max_devices, f.issued, f.expires, f.license_id, f.signature);
    return 0;
}

static int cmd_verify(int argc, char **argv)
{
    if (argc != 2) {
        fprintf(stderr, "usage: license-tool verify FILE\n");
        return 2;
    }
    license_info li;
    license_load(argv[1], &li);
    printf("%s: %s\n", license_status_name(li.status), li.message);
    return li.status == LICENSE_VALID ? 0 : 1;
}

int main(int argc, char **argv)
{
    log_level = LVL_WARN;
    if (argc >= 2 && !strcmp(argv[1], "keygen"))
        return cmd_keygen(argc - 1, argv + 1);
    if (argc >= 2 && !strcmp(argv[1], "sign"))
        return cmd_sign(argc - 1, argv + 1);
    if (argc >= 2 && !strcmp(argv[1], "verify"))
        return cmd_verify(argc - 1, argv + 1);
    fprintf(stderr, "usage: license-tool keygen [--force] | sign --customer NAME --devices N [--days D] | verify FILE\n");
    return 2;
}
